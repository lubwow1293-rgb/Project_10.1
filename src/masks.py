"""
Функция маскировки номера банковской карты
"""


def get_mask_card_number(card_number: str) -> str:
    # 1. Оставляем только цифры, отсекаем пробелы, тире и другие символы
    digits = "".join(filter(str.isdigit, card_number))

    # 2. Проверяем, что номер карты состоит из 16 цифр
    if len(digits) != 16:
        raise ValueError("Номер карты должен содержать ровно 16 цифр")

    # 3. Извлекаем части номера
    first_six = digits[:6]
    last_four = digits[-4:]

    # 4. Формируем строку в требуемом формате
    # Первые две цифры из первой шестерки идут в первый блок,
    # оставшиеся две — в начало второго блока, далее идут звездочки
    masked = f"{first_six[:4]} {first_six[4:]}** **** {last_four}"

    return masked


"""
Функция маскировки номера банковского счета
"""


def get_mask_account(account_number: str) -> str:
    """
    Принимает номер счета в виде строки и возвращает его маску в формате **XXXX.
    """
    # Убираем возможные пробелы по краям
    account_number = account_number.strip()
    # Возвращаем две звездочки и последние 4 символа
    return f"**{account_number[-4:]}"
